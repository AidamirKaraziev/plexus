#!/usr/bin/env python3
"""Проверка отчёта работника и файла роли. Отчёт — слова работника, проверяет машина.

Отчёт — ровно четыре поля, каждое непустое («—» — валидное «нечего сказать»):

    ветка:    работник/отчёт-проверка
    сделал:   lib/отчёт.py — проверка полей и сверка команды
    не смог:  —
    проверка: python3 lib/отчёт.py --самопроверка → ок

    python3 ${CLAUDE_PLUGIN_ROOT}/lib/отчёт.py <отчёт> [--круг <файл круга> [--задача «имя»]]
    python3 ${CLAUDE_PLUGIN_ROOT}/lib/отчёт.py --роль .claude/agents/программист.md
    python3 ${CLAUDE_PLUGIN_ROOT}/lib/отчёт.py --самопроверка
"""
import argparse
import re
import subprocess
import sys
from pathlib import Path

ПОЛЯ = ["ветка", "сделал", "не смог", "проверка"]
FIELD = re.compile(r"^(ветка|сделал|не смог|проверка)\s*:\s*(.*)$", re.I)
ЗАГОЛОВОК = re.compile(r"^###\s+(.+?)(?:\s+·\s+после\s+.*)?$")
ПРОВЕРКА = re.compile(r"^проверка\s*:\s*(.+)$", re.I)

# что обязано быть в файле роли → по каким маркерам узнаём (хватает одного)
РОЛЬ = [
    ("шаблон отчёта: поле «ветка»", ["ветка:"]),
    ("шаблон отчёта: поле «сделал»", ["сделал:"]),
    ("шаблон отчёта: поле «не смог»", ["не смог:"]),
    ("шаблон отчёта: поле «проверка»", ["проверка:"]),
    ("правило «не написано — не делаю»", ["не написано — не делаю", "не написано - не делаю"]),
    ("правило «неясно — стоп и вопрос»", ["неясно — стоп и вопрос", "неясно - стоп и вопрос"]),
    ("запрет трогать файлы вне выданных", ["вне выданных"]),
    ("запрет писать время и токены", ["время и токены"]),
    ("правило «ветка: только имя»", ["ветка: только имя"]),
    ("правило «проверка: команда ровно из задания, затем результат; если прогнал частями — команда целиком, ниже как прогнал»",
     ["проверка: команда ровно из задания, затем результат; если прогнал частями — команда целиком, ниже как прогнал"]),
    ("правило «факт с уликой, предположение помечено»", ["предположени"]),
]


def команда(строка: str) -> str:
    """Из «pytest tests/x.py → 12 passed» — сама команда, без результата."""
    первая = строка.strip().split("\n", 1)[0]  # ниже может быть «как прогонял частями»
    return re.split(r"→|->", первая, 1)[0].strip().rstrip(".").strip()


def разобрать(текст: str) -> dict[str, str]:
    поля, последнее = {}, None
    for строка in текст.splitlines():
        m = FIELD.match(строка.strip())
        if m:
            последнее = m.group(1).lower()
            поля[последнее] = m.group(2).strip()
        elif последнее and строка.strip() and (
                строка.startswith((" ", "\t")) or (
                    последнее == "проверка"
                    and not строка.strip().lower().startswith("предположение"))):
            поля[последнее] += "\n" + строка.strip()
    return поля


def задачи_круга(текст: str) -> dict[str, str]:
    """«имя задачи» → команда из её `проверка:`."""
    out, имя = {}, None
    for строка in текст.splitlines():
        m = ЗАГОЛОВОК.match(строка.strip())
        if m:
            имя = m.group(1).strip().strip("«»")
            continue
        p = ПРОВЕРКА.match(строка.strip())
        if p and имя:
            out[имя] = команда(p.group(1))
            имя = None
    return out


def ветка_есть(имя: str, repo: Path) -> bool:
    r = subprocess.run(
        ["git", "rev-parse", "--verify", "--quiet", f"refs/heads/{имя}"],
        cwd=repo, capture_output=True, text=True,
    )
    return r.returncode == 0


def проверить(текст: str, круг: str | None, задача: str | None, repo: Path | None) -> list[str]:
    беды = []
    поля = разобрать(текст)
    for имя in ПОЛЯ:
        if имя not in поля:
            беды.append(f"нет поля «{имя}»")
        elif not поля[имя]:
            беды.append(f"поле «{имя}» пустое — «—» валидно, пропуск нет")
    if беды:
        return беды

    имя_ветки = поля["ветка"].split()[0]  # «имя (коммит abc)» — берём первый токен
    if repo is not None and not ветка_есть(имя_ветки, repo):
        беды.append(f"ветки «{имя_ветки}» нет в репозитории")

    if круг is not None:
        задачи = задачи_круга(круг)
        моя = команда(поля["проверка"])
        if задача:
            if задача not in задачи:
                беды.append(f"задачи «{задача}» нет в файле круга")
            elif задачи[задача] != моя:
                беды.append(
                    f"команда не та: в задании «{задачи[задача]}», в отчёте «{моя}»")
        elif моя not in задачи.values():
            беды.append(f"команда «{моя}» не совпала ни с одной задачей круга")
    return беды


def проверить_роль(текст: str) -> list[str]:
    # переносы строк и разметка не должны прятать маркер: «вне\nвыданных» — это «вне выданных»
    низ = re.sub(r"\s+", " ", текст.lower().replace("*", "").replace("`", ""))
    return [что for что, маркеры in РОЛЬ if not any(m in низ for m in маркеры)]


ОБРАЗЕЦ = """ветка:    работник/проба
сделал:   lib/отчёт.py — четыре поля и сверка команды
не смог:  —
проверка: python3 lib/отчёт.py --самопроверка → ок
"""
КРУГ = """## Задачи

### Проверка отчёта работника
кому: программист · файлы: lib/отчёт.py
готово, когда: проверяет четыре поля
проверка: python3 lib/отчёт.py --самопроверка

### Уборка дорожек · после «Проверка отчёта работника»
кому: программист · файлы: lib/уборка.py
готово, когда: сносит дорожки
проверка: python3 lib/уборка.py --сухой-прогон
"""


def самопроверка() -> int:
    случаи = [
        ("целый отчёт", ОБРАЗЕЦ, КРУГ, None, []),
        ("задача названа явно", ОБРАЗЕЦ, КРУГ, "Проверка отчёта работника", []),
        ("нет поля", ОБРАЗЕЦ.replace("не смог:  —\n", ""), None, None,
         ["нет поля «не смог»"]),
        ("пустое поле", ОБРАЗЕЦ.replace("не смог:  —", "не смог:"), None, None,
         ["поле «не смог» пустое — «—» валидно, пропуск нет"]),
        ("команда не та",
         ОБРАЗЕЦ.replace("--самопроверка", "--самопроверка-другая"), КРУГ,
         "Проверка отчёта работника",
         ["команда не та: в задании «python3 lib/отчёт.py --самопроверка», "
          "в отчёте «python3 lib/отчёт.py --самопроверка-другая»"]),
        ("команды нет в круге",
         ОБРАЗЕЦ.replace("--самопроверка", "--чужое"), КРУГ, None,
         ["команда «python3 lib/отчёт.py --чужое» не совпала ни с одной задачей круга"]),
        ("нет такой задачи", ОБРАЗЕЦ, КРУГ, "Выдуманная",
         ["задачи «Выдуманная» нет в файле круга"]),
        ("ветка с пояснением", ОБРАЗЕЦ.replace("работник/проба", "работник/проба (коммит e473ddb8)"),
         КРУГ, None, []),
        ("проверка: команда, ниже как прогонял частями",
         ОБРАЗЕЦ.replace("→ ок", "\nчастями: A → ок; B → ок; итог ок"), КРУГ,
         "Проверка отчёта работника", []),
        ("проверка с результатом и пояснением ниже",
         ОБРАЗЕЦ + "предположение: так надёжнее\n", КРУГ, None, []),
    ]
    плохо = 0
    for имя, отчёт, круг, задача, ждём in случаи:
        вышло = проверить(отчёт, круг, задача, None)
        if вышло != ждём:
            плохо += 1
            print(f"✗ {имя}: ждали {ждём}, вышло {вышло}")
    роль = "\n".join(м[0] for _, м in РОЛЬ)
    if проверить_роль(роль) != []:
        плохо += 1
        print(f"✗ роль: полная роль не прошла — {проверить_роль(роль)}")
    if len(проверить_роль("пусто")) != len(РОЛЬ):
        плохо += 1
        print("✗ роль: пустой файл должен провалить все пункты")
    if плохо:
        print(f"самопроверка: {плохо} случаев не сошлись")
        return 1
    print(f"ок · случаев {len(случаи) + 2}")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(add_help=True)
    ap.add_argument("отчёт", nargs="?", help="файл отчёта работника")
    ap.add_argument("--круг", help="файл круга — сверить команду проверки")
    ap.add_argument("--задача", help="имя задачи в файле круга")
    ap.add_argument("--роль", help="проверить файл роли вместо отчёта")
    ap.add_argument("--репозиторий", default=".", help="где искать ветку")
    ap.add_argument("--без-git", action="store_true", help="не проверять ветку")
    ap.add_argument("--самопроверка", action="store_true")
    a = ap.parse_args()

    if a.самопроверка:
        return самопроверка()

    if a.роль:
        путь = Path(a.роль)
        if not путь.exists():
            print(f"нет файла роли: {путь}")
            return 1
        беды = проверить_роль(путь.read_text(encoding="utf-8"))
        if беды:
            for б in беды:
                print(f"✗ {б}")
            return 1
        print("ок")
        return 0

    if not a.отчёт:
        ap.error("нужен файл отчёта, --роль или --самопроверка")
    путь = Path(a.отчёт)
    if not путь.exists():
        print(f"нет файла отчёта: {путь}")
        return 1
    круг = None
    if a.круг:
        p = Path(a.круг)
        if not p.exists():
            print(f"нет файла круга: {p}")
            return 1
        круг = p.read_text(encoding="utf-8")
    repo = None if a.без_git else Path(a.репозиторий)
    беды = проверить(путь.read_text(encoding="utf-8"), круг, a.задача, repo)
    if беды:
        for б in беды:
            print(f"✗ {б}")
        return 1
    print("ок")
    return 0


if __name__ == "__main__":
    sys.exit(main())
