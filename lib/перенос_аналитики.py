class Отказ(Exception):
    """Код 1: неверные аргументы или карта."""


def нфц(s: str) -> str:
    return unicodedata.normalize("NFC", s)


# ---------- источник ----------

def файлы_источника(корень: Path) -> dict[str, Path]:
    """NFC-путь от корня → файл; без .git/ и .DS_Store, по алфавиту."""
    out = {}
    for p in корень.rglob("*"):
        части = p.relative_to(корень).parts
        if ".git" in части or p.name == ".DS_Store" or not p.is_file():
            continue
        out[нфц("/".join(части))] = p
    return dict(sorted(out.items()))


def строки_текста(текст: str) -> list[str]:
    с = текст.replace("\r\n", "\n").replace("\r", "\n").split("\n")
    if с and с[-1] == "":
        с.pop()
    return с


def размеченные(строки: list[str]):
    """(номер, строка, внутри блока кода) — ограды ``` и ~~~."""
    ограда = None
    for i, с in enumerate(строки, 1):
        m = re.match(r"^ {0,3}(`{3,}|~{3,})", с)
        if ограда is None:
            if m:
                ограда = (m.group(1)[0], len(m.group(1)))
            yield i, с, ограда is not None
        else:
            yield i, с, True
            ч = с.strip()
            if ч and set(ч) == {ограда[0]} and len(ч) >= ограда[1]:
                ограда = None


def заголовки(строки: list[str]) -> list[tuple[int, str]]:
    return [(i, с) for i, с, код in размеченные(строки)
            if not код and re.match(r"^#{1,6} ", с)]


def границы_раздела(строки: list[str], имя: str) -> tuple[int, int] | None:
    """[начало, конец) раздела `## имя` (индексы строк); вне блоков кода."""
    начало = None
    for i, с, код in размеченные(строки):
        if код or not с.startswith("## "):
            continue
        if начало is not None:
            return начало, i - 1
        if нфц(с[3:].strip()) == имя:
            начало = i - 1
    return (начало, len(строки)) if начало is not None else None


def заменить_раздел(строки: list[str], имя: str, тело: list[str]) -> list[str]:
    г = границы_раздела(строки, имя)
    новое = ["## " + имя, ""] + тело
    if г is None:
        база = list(строки)
        while база and not база[-1].strip():
            база.pop()
        return база + ([""] if база else []) + новое
    начало, конец = г
    хвост = строки[конец:]
    return строки[:начало] + новое + ([""] + хвост if хвост else [])


# ---------- опись ----------

def опись(папка: Path, метка: str | None) -> dict:
    сегодня = datetime.date.today().isoformat()
    не_знаю = []
    for имя, путь in файлы_источника(папка).items():
        запись: dict = {"файл": имя}
        if имя.lower().endswith(".md"):
            try:
                строки = строки_текста(путь.read_text(encoding="utf-8"))
            except UnicodeDecodeError:
                raise Отказ(f"{имя}: не читается как UTF-8")
            запись["строк"] = len(строки)
            запись["заголовки"] = [{"строка": n, "текст": т} for n, т in заголовки(строки)]
        не_знаю.append(запись)
    return {
        "формат": 1,
        "источник": {"метка": метка or f"снимок {сегодня}", "дата": сегодня,
                     "корень": f"Папка «{папка.name}»; её путь передаётся скрипту аргументом --источник."},
        "шапка аналитики": {"тип работы": "перенос", "этап": "ЧТО", "статус": "черновик",
                            "автор": "перенос из источника (скрипт)", "роль": "аналитик"},
        "модули": {},
        "capability": [],
        "сценарии": [],
        "не переносится": {"файлы": [], "диапазоны": []},
        "типы файлов": ТИПЫ_ПО_УМОЛЧАНИЮ,
        "не знаю, куда": не_знаю,
    }


# ---------- загрузка карты ----------

def _ключи(объект, обяз, необяз, где):
    if not isinstance(объект, dict):
        raise Отказ(f"{где}: ожидался объект")
    for к in обяз:
        if к not in объект:
            raise Отказ(f"{где}: нет ключа «{к}»")
    for к in объект:
        if к not in обяз and к not in необяз:
            raise Отказ(f"{где}: лишний ключ «{к}»")


def _строка(значение, где) -> str:
    if not isinstance(значение, str) or not значение.strip():
        raise Отказ(f"{где}: пустое или не строка")
    return нфц(значение.strip())


def _список(значение, где) -> list:
    if not isinstance(значение, list):
        raise Отказ(f"{где}: ожидался список")
    return значение


def _путь(значение, где, расширение: str | None = None) -> str:
    п = _строка(значение, где)
    if п.startswith("/") or "\\" in п:
        raise Отказ(f"{где}: путь от корня источника, с «/», без начального «/»: {п}")
    if расширение and not п.lower().endswith(расширение):
        raise Отказ(f"{где}: ожидался файл {расширение}: {п}")
    return п


def _диапазон(строки, заголовок, где):
    """(первая, последняя, заголовок) или None, если нет обоих ключей."""
    if строки is None and заголовок is None:
        return None
    if (not isinstance(строки, list) or len(строки) != 2
            or not all(isinstance(x, int) and not isinstance(x, bool) for x in строки)):
        raise Отказ(f"{где}: «строки» — [первая, последняя], целые")
    if строки[0] < 1 or строки[0] > строки[1]:
        raise Отказ(f"{где}: «строки» — нужно 1 ≤ первая ≤ последняя")
    return (строки[0], строки[1], _строка(заголовок, f"{где}.заголовок"))


def загрузить_карту(путь: Path) -> dict:
    try:
        сырая = json.loads(путь.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError) as e:
        raise Отказ(f"карта не читается: {e}")
    except json.JSONDecodeError as e:
        raise Отказ(f"карта не читается как JSON: {e}")
    if not isinstance(сырая, dict):
        raise Отказ("карта: корень — не объект")
    if сырая.get("формат") != 1 or isinstance(сырая.get("формат"), bool):
        raise Отказ("формат не поддерживается: нужен 1")
    _ключи(сырая, КОРНЕВЫЕ, [], "карта")
    к: dict = {}

    ист = сырая["источник"]
    _ключи(ист, ["метка", "дата", "корень"], [], "источник")
    к["метка"] = _строка(ист["метка"], "источник.метка")
    if not re.fullmatch(r"\d{4}-\d{2}-\d{2}", _строка(ист["дата"], "источник.дата")):
        raise Отказ("источник.дата: нужна ГГГГ-ММ-ДД")
    _строка(ист["корень"], "источник.корень")

    ш = сырая["шапка аналитики"]
    _ключи(ш, ["тип работы", "этап", "статус", "автор", "роль"], [], "шапка аналитики")
    к["шапка"] = {x: _строка(ш[x], f"шапка аналитики.{x}") for x in ш}
    if к["шапка"]["тип работы"] not in ТИПЫ_РАБОТЫ:
        raise Отказ(f"шапка аналитики.тип работы: из {', '.join(ТИПЫ_РАБОТЫ)}")
    if к["шапка"]["статус"] != "черновик":
        raise Отказ("шапка аналитики.статус: в этой версии только «черновик»")

    if not isinstance(сырая["модули"], dict):
        raise Отказ("модули: ожидался объект")
    к["модули"] = {}
    for ключ, папка in сырая["модули"].items():
        папка = _строка(папка, f"модули.{ключ}")
        m = МОДУЛЬ.match(папка)
        if not m or m.group(1) != ключ:
            raise Отказ(f"модули.{ключ}: ключ должен совпадать с <en> в «<рус> (<en>)»")
        к["модули"][ключ] = папка

    к["capability"] = []
    пары, коды = set(), set()
    for i, c in enumerate(_список(сырая["capability"], "capability")):
        где = f"capability[{i}]"
        _ключи(c, ["модуль", "capability", "код", "название", "за что отвечает", "владелец таблиц"], [], где)
        з = {x: _строка(c[x], f"{где}.{x}") for x in ["модуль", "capability", "код", "название", "за что отвечает"]}
        if з["модуль"] not in к["модули"]:
            raise Отказ(f"{где}: модуль «{з['модуль']}» нет в «модули»")
        з["таблицы"] = [_строка(t, f"{где}.владелец таблиц")
                        for t in _список(c["владелец таблиц"], f"{где}.владелец таблиц")]
        if (з["модуль"], з["capability"]) in пары:
            raise Отказ(f"{где}: пара {з['модуль']}+{з['capability']} повторяется")
        if з["код"] in коды:
            raise Отказ(f"{где}: повтор кода «{з['код']}»")
        пары.add((з["модуль"], з["capability"]))
        коды.add(з["код"])
        к["capability"].append(з)
    по_паре = {(c["модуль"], c["capability"]): c for c in к["capability"]}
    по_имени = defaultdict(list)
    for c in к["capability"]:
        по_имени[c["capability"]].append(c)

    к["сценарии"] = []
    сц_коды = set()
    for i, s in enumerate(_список(сырая["сценарии"], "сценарии")):
        где = f"сценарии[{i}]"
        _ключи(s, ["код", "название", "модуль", "capability", "затрагивает", "источники", "кадры", "sql"],
               ["кадры вне источника", "ссылки без файла", "спорно"], где)
        з = {x: _строка(s[x], f"{где}.{x}") for x in ["код", "название", "модуль", "capability"]}
        if (з["модуль"], з["capability"]) not in по_паре:
            raise Отказ(f"{где}: сценарий в неизвестной capability {з['модуль']}+{з['capability']}")
        cap = по_паре[(з["модуль"], з["capability"])]
        m = re.fullmatch(r"(.+)-(\d{2,})", з["код"])
        if not m or m.group(1) != cap["код"]:
            raise Отказ(f"{где}: код «{з['код']}» должен быть {cap['код']}-NN")
        if з["код"] in сц_коды:
            raise Отказ(f"{где}: повтор кода «{з['код']}»")
        сц_коды.add(з["код"])
        if " — " not in з["название"]:
            raise Отказ(f"{где}: название «что делаем — какая проблема» (с « — »)")
        з["затрагивает"] = [_строка(x, f"{где}.затрагивает") for x in _список(s["затрагивает"], f"{где}.затрагивает")]
        for имя in з["затрагивает"]:
            if имя == з["capability"]:
                raise Отказ(f"{где}: затрагивает саму себя «{имя}»")
            if имя not in по_имени:
                raise Отказ(f"{где}: затрагивает неизвестную capability «{имя}»")
            if len(по_имени[имя]) > 1:
                raise Отказ(f"{где}: затрагивает «{имя}» — имя неоднозначно, capability в нескольких модулях")
        исходники = _список(s["источники"], f"{где}.источники")
        if not исходники:
            raise Отказ(f"{где}.источники: пуст")
        з["источники"] = []
        for j, it in enumerate(исходники):
            г = f"{где}.источники[{j}]"
            _ключи(it, ["файл"], ["строки", "заголовок"], г)
            if ("строки" in it) != ("заголовок" in it):
                raise Отказ(f"{г}: «строки» и «заголовок» только вместе")
            з["источники"].append({"файл": _путь(it["файл"], г),
                                   "диапазон": _диапазон(it.get("строки"), it.get("заголовок"), г)})
        з["кадры"] = [_путь(x, f"{где}.кадры", ".png") for x in _список(s["кадры"], f"{где}.кадры")]
        з["sql"] = [_путь(x, f"{где}.sql", ".sql") for x in _список(s["sql"], f"{где}.sql")]
        з["вне"] = [_строка(x, f"{где}.кадры вне источника")
                    for x in _список(s.get("кадры вне источника", []), f"{где}.кадры вне источника")]
        з["без файла"] = [_строка(x, f"{где}.ссылки без файла")
                          for x in _список(s.get("ссылки без файла", []), f"{где}.ссылки без файла")]
        з["спорно"] = _строка(s["спорно"], f"{где}.спорно") if "спорно" in s else ""
        к["сценарии"].append(з)

    нп = сырая["не переносится"]
    _ключи(нп, ["файлы", "диапазоны"], [], "не переносится")
    к["не_файлы"] = {}
    for i, e in enumerate(_список(нп["файлы"], "не переносится.файлы")):
        г = f"не переносится.файлы[{i}]"
        _ключи(e, ["файл", "причина"], [], г)
        к["не_файлы"][_путь(e["файл"], г)] = _строка(e["причина"], f"{г}.причина")
    к["не_диапазоны"] = []
    for i, e in enumerate(_список(нп["диапазоны"], "не переносится.диапазоны")):
        г = f"не переносится.диапазоны[{i}]"
        _ключи(e, ["файл", "строки", "заголовок", "причина"], [], г)
        _строка(e["причина"], f"{г}.причина")
        к["не_диапазоны"].append({"файл": _путь(e["файл"], г),
                                  "диапазон": _диапазон(e["строки"], e["заголовок"], г)})

    if not isinstance(сырая["типы файлов"], dict):
        raise Отказ("типы файлов: ожидался объект")
    к["типы"] = {}
    for расш, правило in сырая["типы файлов"].items():
        г = f"типы файлов.{расш}"
        _ключи(правило, ["действие", "причина"], ["куда"], г)
        if правило["действие"] not in ДЕЙСТВИЯ:
            raise Отказ(f"{г}: действие из: {'; '.join(ДЕЙСТВИЯ)}")
        _строка(правило["причина"], f"{г}.причина")
        if расш != нфц(расш).lower():
            raise Отказ(f"{г}: расширение строчными, без точки")
        к["типы"][расш] = правило["действие"]

    к["не_знаю"] = []
    for i, e in enumerate(_список(сырая["не знаю, куда"], "не знаю, куда")):
        if isinstance(e, str):
            к["не_знаю"].append(нфц(e))
        elif isinstance(e, dict) and "файл" in e:
            к["не_знаю"].append(_путь(e["файл"], f"не знаю, куда[{i}]"))
        else:
            raise Отказ(f"не знаю, куда[{i}]: строка-путь или объект с «файл»")
    return к


