def дописать_ссылки(строки: list[str], раздел: str, цели: list[str]) -> list[str]:
    г = границы_раздела(строки, раздел)
    есть: set[str] = set()
    тело: list[str] = []
    if г:
        тело = строки[г[0] + 1:г[1]]
        есть = {нфц(re.split(r"[|#]", m, 1)[0].strip())
                for m in re.findall(r"\[\[([^\[\]]+)\]\]", "\n".join(тело))}
    нет = [ц for ц in dict.fromkeys(цели) if нфц(ц) not in есть]
    if not нет:
        return строки
    ссылки = " ".join(f"[[{ц}]]" for ц in нет)
    содержимое = [x for x in тело if x.strip()]
    if not содержимое or (not есть and содержимое[0].startswith("Пока нет")):
        новое = [ссылки]
    elif есть:
        новое = содержимое[:-1] + [содержимое[-1] + " " + ссылки]
    else:
        новое = содержимое + ["", ссылки]
    return заменить_раздел(строки, раздел, новое)


def прочитать_строки(путь: Path) -> list[str]:
    строки = путь.read_text(encoding="utf-8").split("\n")
    if строки and строки[-1] == "":
        строки.pop()
    return строки


def прогон(карта: dict, ист: Источник, vault: Path, сухой: bool) -> list[str]:
    """Считает и, если не сухой, делает; возвращает строки плана."""
    сегодня = datetime.date.today().isoformat()
    глагол = {"карточка": ("создам карточку", "создал карточку"),
              "ссылки": ("допишу ссылки в карточку", "дописал ссылки в карточку"),
              "заготовка": ("создам заготовку", "создал заготовку"),
              "источник": ("перепишу Источник в", "переписал Источник в"),
              "кадр": ("скопирую кадр", "скопировал кадр")}
    план: list[str] = []
    записи: dict[Path, bytes | str] = {}

    def записать(вид: str, путь: Path, содержимое):
        if путь in записи:
            return
        план.append(f"{глагол[вид][0 if сухой else 1]} {путь.relative_to(vault).as_posix()}")
        записи[путь] = содержимое

    по_паре = {(c["модуль"], c["capability"]): c for c in карта["capability"]}
    по_имени = {c["capability"]: c for c in карта["capability"]}

    заготовки: dict[str, Path] = {}
    for s in карта["сценарии"]:
        папка = папка_capability(vault, карта, по_паре[(s["модуль"], s["capability"])])
        найдено = найденная_заготовка(папка, s["код"])
        заготовки[s["код"]] = найдено[0] if найдено else папка / "аналитика" / f"{s['код']} {s['название']}.md"

    свои: dict[tuple, list[str]] = defaultdict(list)
    входящие: dict[tuple, list[str]] = defaultdict(list)
    for s in карта["сценарии"]:
        основа = заготовки[s["код"]].name[:-3]
        свои[(s["модуль"], s["capability"])].append(основа)
        for имя in s["затрагивает"]:
            c = по_имени[имя]
            входящие[(c["модуль"], c["capability"])].append(основа)

    for s in карта["сценарии"]:
        путь = заготовки[s["код"]]
        источник = раздел_источник(карта, ист, s)
        if путь.exists():
            было = прочитать_строки(путь)
            новые = заменить_раздел(было, "Источник", источник)
            вид = "источник"
        else:
            ш = карта["шапка"]
            шапка = ["---", f"код: {s['код']}", f"название: {s['название']}",
                     f"модуль: {карта['модули'][s['модуль']]}", f"capability: {s['capability']}",
                     f"затрагивает: [{', '.join(s['затрагивает'])}]", f"тип работы: {ш['тип работы']}",
                     f"этап: {ш['этап']}", f"статус: {ш['статус']}", f"автор: {ш['автор']}",
                     f"роль: {ш['роль']}", f"дата: {сегодня}", 'верно: {кто: "", дата: ""}',
                     'понятно: {кто: "", дата: ""}', 'youtrack: ""', "круги: []", "решения: []", "---"]
            тело = тело_шаблона("аналитика.md")
            for i, с in enumerate(тело):
                if с.startswith("# "):
                    тело[i] = f"# {s['код']} {s['название']}"
                    break
            while тело and not тело[-1].strip():
                тело.pop()
            было = None
            новые = заменить_раздел(шапка + тело, "Источник", источник)
            вид = "заготовка"
        if новые != было:
            записать(вид, путь, "\n".join(новые) + "\n")

    for cap in карта["capability"]:
        путь = папка_capability(vault, карта, cap) / "capability.md"
        ключ = (cap["модуль"], cap["capability"])
        if путь.exists():
            было, вид = прочитать_строки(путь), "ссылки"
        else:
            было, вид = новая_карточка(карта, cap), "карточка"
        новые = дописать_ссылки(было, "Своя аналитика", свои.get(ключ, []))
        новые = дописать_ссылки(новые, "Меня затрагивают", входящие.get(ключ, []))
        if вид == "карточка" or новые != было:
            записать(вид, путь, "\n".join(новые) + "\n")

    for s in карта["сценарии"]:
        папка = папка_capability(vault, карта, по_паре[(s["модуль"], s["capability"])])
        for п in s["кадры"] + s["sql"]:
            цель = папка / "аналитика" / ПАПКА_КАДРОВ / posixpath.basename(п)
            данные = ист.файлы[п].read_bytes()
            if not цель.exists() or цель.read_bytes() != данные:
                записать("кадр", цель, данные)

    if not сухой:
        for путь, содержимое in записи.items():
            путь.parent.mkdir(parents=True, exist_ok=True)
            if isinstance(содержимое, bytes):
                путь.write_bytes(содержимое)
            else:
                путь.write_text(содержимое, encoding="utf-8")
    return план


