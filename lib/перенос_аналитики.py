def main() -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    ap = argparse.ArgumentParser(description="Перенос аналитики по карте формата 1 (skills/analysis/перенос.md)")
    ap.add_argument("--опись", metavar="ПАПКА")
    ap.add_argument("--метка")
    ap.add_argument("--выход")
    ap.add_argument("--карта")
    ap.add_argument("--источник")
    ap.add_argument("--vault")
    ap.add_argument("--сухой", action="store_true")
    ap.add_argument("--самопроверка", action="store_true")
    a = ap.parse_args()
    try:
        if a.самопроверка:
            return самопроверка()
        if a.опись:
            папка = Path(a.опись)
            if not папка.is_dir():
                raise Отказ(f"нет папки источника: {папка}")
            текст = json.dumps(опись(папка, a.метка), ensure_ascii=False, indent=2) + "\n"
            if a.выход:
                Path(a.выход).write_text(текст, encoding="utf-8")
            else:
                sys.stdout.write(текст)
            return 0
        if a.карта and a.источник and a.vault:
            return применить(Path(a.карта), Path(a.источник), Path(a.vault), a.сухой)
        raise Отказ("нужно одно из: --опись, --карта с --источник и --vault, --самопроверка")
    except Отказ as e:
        print(str(e), file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
