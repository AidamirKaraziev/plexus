class Источник:
    """Файлы источника и их строки с кэшем."""

    def __init__(self, корень: Path):
        self.файлы = файлы_источника(корень)
        self._строки: dict[str, list[str] | None] = {}

    def строки(self, имя: str) -> list[str] | None:
        if имя not in self._строки:
            try:
                self._строки[имя] = строки_текста(self.файлы[имя].read_text(encoding="utf-8"))
            except UnicodeDecodeError:
                self._строки[имя] = None
        return self._строки[имя]


def папка_capability(vault: Path, карта: dict, cap: dict) -> Path:
    return vault / "модули" / карта["модули"][cap["модуль"]] / cap["capability"]


def найденная_заготовка(папка: Path, код: str) -> list[Path]:
    дир = папка / "аналитика"
    if not дир.is_dir():
        return []
    return sorted(p for p in дир.iterdir()
                  if p.is_file() and нфц(p.name).startswith(код + " ") and p.suffix == ".md")


def сверить(карта: dict, ист: Источник, vault: Path) -> list[str]:
    причины: list[str] = []

    def отказ(файл: str, строки, текст: str):
        адрес = файл + (f": строки {строки[0]}–{строки[1]}" if строки else "")
        строка = f"{адрес}: {текст}"
        if строка not in причины:
            причины.append(строка)

    for файл in карта["не_знаю"]:
        отказ(файл, None, "в списке «не знаю, куда» карты")

    упомянутые = list(карта["не_файлы"]) + [d["файл"] for d in карта["не_диапазоны"]]
    for s in карта["сценарии"]:
        упомянутые += [i["файл"] for i in s["источники"]] + s["кадры"] + s["sql"]
    for файл in dict.fromkeys(упомянутые):
        if файл not in ист.файлы:
            отказ(файл, None, "файла из карты нет в источнике")

    покрытие: dict[str, list[tuple[int, int]]] = defaultdict(list)
    целиком: set[str] = set()

    def проверить_диапазон(кто: str, файл: str, диап):
        if файл not in ист.файлы:
            return
        строки = ист.строки(файл)
        if строки is None:
            отказ(файл, None, "не читается как UTF-8")
            return
        a, b, заголовок = диап
        if b > len(строки):
            отказ(файл, (a, b), f"диапазон за концом файла (в файле {len(строки)} строк) — {кто}")
            return
        найдено = строки[a - 1]
        if нфц(найдено) != заголовок:
            отказ(файл, (a, b), f"заголовок не на своей строке ({кто}): ожидался «{заголовок}», найдено «{найдено}»")
        покрытие[файл].append((a, b))

    for s in карта["сценарии"]:
        for it in s["источники"]:
            if it["диапазон"] is None:
                целиком.add(it["файл"])
                if it["файл"] in ист.файлы and ист.строки(it["файл"]) is None:
                    отказ(it["файл"], None, "не читается как UTF-8")
            else:
                проверить_диапазон(f"сценарий {s['код']}", it["файл"], it["диапазон"])
    for d in карта["не_диапазоны"]:
        проверить_диапазон("не переносится", d["файл"], d["диапазон"])

    for файл in sorted(set(покрытие) - целиком - set(карта["не_файлы"])):
        строки = ист.строки(файл) or []
        занято = [False] * (len(строки) + 2)
        for a, b in покрытие[файл]:
            for n in range(a, min(b, len(строки)) + 1):
                занято[n] = True
        n = 1
        while n <= len(строки):
            if not занято[n]:
                m = n
                while m + 1 <= len(строки) and not занято[m + 1]:
                    m += 1
                отказ(файл, (n, m), "дыра в покрытии: не знаю, куда")
                n = m
            n += 1

    решённые = set(карта["не_файлы"]) | целиком | set(покрытие)
    копируемые = {п for s in карта["сценарии"] for п in s["кадры"] + s["sql"]}
    for файл in ист.файлы:
        if файл in решённые or файл in копируемые:
            continue
        имя = posixpath.basename(файл)
        расш = имя.rsplit(".", 1)[1].lower() if "." in имя else ""
        действие = карта["типы"].get(расш) if расш else None
        if действие is None:
            действие = карта["типы"].get("прочие", "не знаю, куда")
        if действие in ("не переносится", КОПИРУЕТСЯ):
            continue  # назван в кадры/sql — копируется (выше), иначе пропускается
        отказ(файл, None, "файл вне карты («не знаю, куда»)")

    for s in карта["сценарии"]:
        в_списках = set(s["кадры"]) | set(s["sql"])
        вне = {posixpath.normpath(x) for x in s["вне"]}
        for it in s["источники"]:
            файл = it["файл"]
            строки = ист.строки(файл) if файл in ист.файлы else None
            if строки is None:
                continue
            диап = it["диапазон"]
            if диап is not None:
                if диап[1] > len(строки):
                    continue
                строки = строки[диап[0] - 1:диап[1]]
            адрес = (диап[0], диап[1]) if диап else None
            for ссылка in dict.fromkeys(ССЫЛКА_НА_ФАЙЛ.findall("\n".join(строки))):
                ссылка = нфц(ссылка)
                c1 = posixpath.normpath(posixpath.join(posixpath.dirname(файл), ссылка))
                c2 = posixpath.normpath(ссылка)
                внутри = next((c for c in (c1, c2) if c in ист.файлы), None)
                if внутри is None:
                    одинаковые = [f for f in ист.файлы if posixpath.basename(f) == posixpath.basename(ссылка)]
                    if len(одинаковые) == 1:
                        внутри = одинаковые[0]
                if внутри is not None:
                    if внутри not in в_списках:
                        отказ(файл, адрес, f"ссылка «{ссылка}» ведёт в {внутри}, а его нет в кадры/sql "
                                           f"сценария {s['код']}")
                elif not (c1 in вне or c2 in вне or any(слово in ссылка for слово in s["без файла"])):
                    отказ(файл, адрес, f"ссылка «{ссылка}» без файла и без места в «кадры вне источника» "
                                       f"или «ссылки без файла» сценария {s['код']}")

    for cap in карта["capability"]:
        по_имени: dict[str, set[str]] = defaultdict(set)
        for s in карта["сценарии"]:
            if (s["модуль"], s["capability"]) == (cap["модуль"], cap["capability"]):
                for п in s["кадры"] + s["sql"]:
                    по_имени[posixpath.basename(п)].add(п)
        for имя, пути in sorted(по_имени.items()):
            if len(пути) > 1:
                отказ(sorted(пути)[0], None,
                      f"два разных файла с именем «{имя}» в capability {cap['capability']}: "
                      + ", ".join(sorted(пути)))
    по_паре = {(c["модуль"], c["capability"]): c for c in карта["capability"]}
    for s in карта["сценарии"]:
        cap = по_паре[(s["модуль"], s["capability"])]
        найдено = найденная_заготовка(папка_capability(vault, карта, cap), s["код"])
        if len(найдено) > 1:
            отказ(s["код"], None, "в папке аналитики больше одной заготовки с этим кодом: "
                  + ", ".join(p.name for p in найдено))
    return причины


