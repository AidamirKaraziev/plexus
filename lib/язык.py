import re
import subprocess
import sys
import tempfile
from pathlib import Path

МАКС_СЛОВ_В_ФРАЗЕ = 20
МАКС_ЦЕПОЧКА = 3

# Единицы величин: слово после числа, начинающееся с одной из этих основ
# (нижний регистр), считается единицей. Список взят из круга «сторож текста»:
# токены, k, ч, часы, мин, с, $, %, строк, слов, задач, файлов, раз, шт.
# К ним добавлены близкие формы: секунды, проценты, дни, рубли.
ЕДИНИЦЫ_ОСНОВЫ = (
    "токен", "час", "мин", "сек", "строк", "слов", "задач", "файл",
    "раз", "шт", "процент", "дн", "день", "дней", "руб", "долл",
)
ЕДИНИЦЫ_ТОЧНО = {"k", "к", "ч", "с", "$", "%", "m", "м"}
# Слова-величины: число после них без единицы — нарушение (П11).
# К ним добавляются термины словаря с заполненной единицей.
ВЕЛИЧИНЫ_СВОИ = (
    "лимит", "расход", "бюджет", "стоимость", "затраты", "время",
    "размер", "длина", "окно", "цена", "скорость",
)

# Слова перед «считаемым» числом: счёт и номер, не величина.
ПРЕДЛОГИ_ЦЕПОЧКИ = {
    "после", "перед", "через", "между", "около", "возле", "вместо",
    "кроме", "ради", "мимо", "среди", "более", "менее",
}
ЗАВЕРШЕНИЯ_РОДИТЕЛЬНОГО = ("ов", "ев", "ей", "а", "я", "ы", "и")
НЕ_РОДИТЕЛЬНЫЙ = ("ла", "ли", "ши", "жи", "чи", "ся", "сь", "ми")

ПОЛЯ_ОТЧЁТА = ("ветка", "сделал", "не смог", "проверка")
НЕТ_КОММИТА = re.compile(
    r"коммит\w*\s+нет|нет\s+коммит\w*|без\s+коммит\w*|не\s+закоммит\w*|"
    r"не\s+коммитил\w*|коммит\w*\s+не\s+(?:сделан\w*|созда\w*)",
    re.I,
)
ХЭШ = re.compile(r"[0-9a-f]{7,40}")
СТОП_В_НАЧАЛЕ = re.compile(r"^(стопы?|не\s+трогаем|не\s+трогай|закрыто)\b", re.I)
НАЧАЛО_ШАГА = re.compile(r"^\s*(?:шаг\s*\d+|\d+[.)]\s|#+\s*шаги\b|шаги\s*:?\s*$)", re.I)

# Что не проверяем: код, ссылки, цитаты, пути, даты, версии, хэши, id.
МАСКИ = [
    re.compile(r"`[^`\n]*`"),
    re.compile(r"\[\[[^\]\n]*\]\]"),
    re.compile(r"«[^»\n]*»"),
    re.compile(r"„[^“\n]*“"),
    re.compile(r"“[^”\n]*”"),
    re.compile(r"<[^>\n]*>"),
    re.compile(r"https?://\S+"),
    re.compile(r"\S*\w/\w\S*"),
    re.compile(r"\S+\.(?:md|py|sh|jsonl?|txt|ya?ml|toml|html|js|css)\b"),
    re.compile(r"\d{4}-\d{2}-\d{2}|\d{1,2}\.\d{1,2}\.\d{2,4}|\d{1,2}:\d{2}"),
    re.compile(r"(?<![\w.])v?\d+\.\d+(?:\.\d+)*(?:-[\w.]+)?(?!\w)"),
    re.compile(r"\b(?=[0-9a-f]*\d)(?=[0-9a-f]*[a-f])[0-9a-f]{7,40}\b"),
    re.compile(r"(?<!\w)[A-ZА-ЯЁ]{1,2}\d{1,3}(?:-[A-ZА-ЯЁ]\d{1,3})*(?!\w)"),
]
СОКРАЩЕНИЕ = re.compile(r"\bт\.\s?[дпе]\.", re.I)
ЧИСЛО = re.compile(r"(?<![\w.,/-])(\d+(?:[  ]\d{3})*(?:[.,]\d+)?)(?![\w]?\d)")


# ---------- словари ----------

class Словарь:
    def __init__(self) -> None:
        self.термины: dict[str, tuple[str, list[str]]] = {}  # термин -> (единица, синонимы)
        self.расплывчатые: dict[str, str] = {}  # слово -> чем заменить


def _ячейки(строка: str) -> list[str]:
    return [c.strip().strip("`") for c in строка.strip().strip("|").split("|")]


def прочитать_словарь(путь: Path, в: Словарь) -> None:
    """Читает таблицы markdown; записи перекрывают уже лежащие в `в`."""
    if not путь.is_file():
        return
    строки = путь.read_text(encoding="utf-8").splitlines()
    заголовок: list[str] | None = None
    for i, с in enumerate(строки):
        if not с.lstrip().startswith("|"):
            заголовок = None
            continue
        ячейки = _ячейки(с)
        след = строки[i + 1] if i + 1 < len(строки) else ""
        if re.fullmatch(r"\|?[\s:|-]+\|?", след.strip()) and "-" in след:
            заголовок = [c.lower() for c in ячейки]
            continue
        if re.fullmatch(r"[\s:|-]*", с.replace("|", "")):
            continue
        if not заголовок or not ячейки or not ячейки[0]:
            continue
        if заголовок[0] == "термин" and len(ячейки) >= 4:
            синонимы = [
                x.strip().lower() for x in ячейки[3].split(",")
                if x.strip() and x.strip() not in ("—", "-")
            ]
            в.термины[ячейки[0].lower()] = (ячейки[2].lower(), синонимы)
        elif заголовок[0] == "слово" and len(ячейки) >= 2:
            в.расплывчатые[ячейки[0].lower()] = ячейки[1]


def корень_git() -> Path:
    try:
        вывод = subprocess.run(
            ["git", "rev-parse", "--show-toplevel"],
            capture_output=True, text=True, timeout=10,
        )
        if вывод.returncode == 0 and вывод.stdout.strip():
            return Path(вывод.stdout.strip())
    except (OSError, subprocess.SubprocessError):
        pass
    return Path(__file__).resolve().parent.parent


def загрузить_словарь(проект: Path | None, база: Path | None = None) -> Словарь:
    словарь = Словарь()
    базовый = база or Path(__file__).resolve().parent / "язык" / "словарь.md"
    прочитать_словарь(базовый, словарь)
    if проект is None:
        кандидат = корень_git() / "vault"
        проект = кандидат if (кандидат / "словарь.md").is_file() else None
    if проект is not None:
        прочитать_словарь(проект / "словарь.md", словарь)
    # Синоним, который сам стал термином, не запрещён: действует проектный.
    имена = set(словарь.термины)
    for имя, (ед, син) in list(словарь.термины.items()):
        словарь.термины[имя] = (ед, [x for x in син if x not in имена])
    return словарь


# Падежные окончания для слов словаря. Основа — слово без последней гласной.
# Склоняем только слова на «а», «я» или согласную (существительные): наречия и
# глаголы («быстро», «улучшить») остаются в одной форме, чтобы не ловить
# «скорой», «быстрые» и прочие однокоренные.
ОКОНЧАНИЯ = ("ами", "ой", "ою", "ам", "ах", "ов", "ом", "ей", "а", "ы", "е", "у", "и", "я", "ю")


def _формы(слово: str) -> str:
    низ = слово.lower()
    if len(низ) < 3 or not низ.isalpha() or низ[-1] not in "аяйбвгджзклмнпрстфхцчшщ":
        return re.escape(слово)
    основа = низ[:-1] if низ[-1] in "ая" else низ
    окончания = "|".join(ОКОНЧАНИЯ)
    return rf"(?:{re.escape(слово)}|{re.escape(основа)}(?:{окончания}))"


def _шаблон(фраза: str, склонять: bool = False) -> re.Pattern:
    слова = фраза.split()
    части = [re.escape(p) for p in слова]
    if склонять and слова:
        части[0] = _формы(слова[0])
    return re.compile(r"(?<!\w)" + r"\s+".join(части) + r"(?!\w)", re.I)


class Движок:
    """Подготовленные шаблоны словаря."""

    def __init__(self, словарь: Словарь) -> None:
        self.синонимы = []  # (шаблон, синоним, термин)
        for термин, (_, син) in словарь.термины.items():
            for с in син:
                self.синонимы.append((_шаблон(с, len(с.split()) == 1), с, термин))
        self.расплывчатые = [(_шаблон(с, len(с.split()) == 1), с, чем) for с, чем in словарь.расплывчатые.items()]
        защита = list(словарь.термины)
        for слово, чем in словарь.расплывчатые.items():
            # «база знаний» в колонке замены — допустимое употребление слова «база».
            for q in re.findall(r"«([^»]+)»", чем):
                if q.lower().startswith(слово.split()[0]):
                    защита.append(q.lower())
        self.защита = [_шаблон(з, True) for з in защита]
        величины = [
            т for т, (ед, _) in словарь.термины.items() if ед and ед not in ("—", "-")
        ] + list(ВЕЛИЧИНЫ_СВОИ)
        альтернативы = sorted(set(величины), key=len, reverse=True)
        self.величина = re.compile(
            r"(?<!\w)(?:" + "|".join(re.escape(a) for a in альтернативы) + r")\w*[\s:=—–-]*$",
            re.I,
        )


# ---------- разбор текста ----------

def замаскировать(строка: str) -> str:
    for м in МАСКИ:
        строка = м.sub(lambda x: " " * len(x.group()), строка)
    return строка


def убрать_разметку(строка: str) -> str:
    строка = re.sub(r"^\s*(?:#+\s+|[-*+]\s+|\d+[.)]\s+|>\s*)", "", строка)
    return строка.replace("**", "").replace("__", "")


def строки_для_проверки(текст: str, пропускать_код: bool):
    """Отдаёт (номер строки с 1, сырая строка) без шапки, кода и таблиц."""
    строки = текст.splitlines()
    i = 0
    if строки and строки[0].strip() == "---":
        for j in range(1, len(строки)):
            if строки[j].strip() == "---":
                i = j + 1
                break
    в_коде = False
    for n in range(i, len(строки)):
        с = строки[n]
        if с.lstrip().startswith("```"):
            if пропускать_код:
                в_коде = not в_коде
            continue
        if в_коде or с.lstrip().startswith("|") or not с.strip():
            continue
        yield n + 1, с


# ---------- проверки ----------

def _защищено(движок: Движок, строка: str) -> list[tuple[int, int]]:
    return [m.span() for п in движок.защита for m in п.finditer(строка)]


def проверка_слов(движок: Движок, номер: int, чистая: str) -> list[tuple[int, str]]:
    """П1 и П2: запрещённые синонимы и расплывчатые слова."""
    нашли = []
    защита = _защищено(движок, чистая)

    def внутри(m: re.Match) -> bool:
        return any(s <= m.start() and m.end() <= e for s, e in защита)

    for шаблон, синоним, термин in движок.синонимы:
        for m in шаблон.finditer(чистая):
            if not внутри(m):
                нашли.append((номер, f"запрещённый синоним «{синоним}»: бери термин «{термин}»"))
    for шаблон, слово, чем in движок.расплывчатые:
        for m in шаблон.finditer(чистая):
            if not внутри(m):
                нашли.append((номер, f"расплывчатое слово «{слово}»: замени — {чем}"))
    return нашли


def _единица(следом: str) -> bool:
    м = re.match(r"\s*([%$]|[^\W\d_]+)", следом)
    if not м:
        return False
    слово = м.group(1).lower()
    return слово in ЕДИНИЦЫ_ТОЧНО or слово.startswith(ЕДИНИЦЫ_ОСНОВЫ)


def проверка_чисел(движок: Движок, номер: int, чистая: str) -> list[tuple[int, str]]:
    """П11: число после слова-величины без единицы. Остальное не трогаем."""
    нашли = []
    for m in ЧИСЛО.finditer(чистая):
        if _единица(чистая[m.end():]):
            continue
        if движок.величина.search(чистая[:m.start()]):
            нашли.append((номер, f"число «{m.group(1)}» без единицы"))
    return нашли


def _родительный(слово: str) -> bool:
    с = слово.lower()
    return (
        len(с) >= 5 and с.isalpha() and с.endswith(ЗАВЕРШЕНИЯ_РОДИТЕЛЬНОГО)
        and not с.endswith(НЕ_РОДИТЕЛЬНЫЙ)
    )


def проверка_длины(номер: int, чистая: str) -> list[tuple[int, str]]:
    """П3: фраза длиннее 20 слов."""
    нашли = []
    текст = СОКРАЩЕНИЕ.sub("тд", чистая)
    for фраза in re.split(r"[.!?;…:→]+(?:\s|$)", текст):
        слов = re.findall(r"[^\W_]+(?:-[^\W_]+)*", фраза)
        if len(слов) > МАКС_СЛОВ_В_ФРАЗЕ:
            нашли.append((номер, f"фраза из {len(слов)} слов, нужно не больше {МАКС_СЛОВ_В_ФРАЗЕ}"))
    return нашли


def проверка_цепочки(номер: int, чистая: str) -> list[tuple[int, str]]:
    """П9: родительная цепочка длиннее 3 существительных (эвристика по окончаниям)."""
    токены = re.findall(r"[^\W_]+(?:-[^\W_]+)*|[^\w\s]", чистая)
    нашли = []
    i = 0
    while i < len(токены):
        if _родительный(токены[i]):
            j = i
            while j < len(токены) and _родительный(токены[j]):
                j += 1
            длина = j - i
            if i > 0 and токены[i - 1].isalpha():
                голова = токены[i - 1].lower()
                if len(голова) >= 4 and голова not in ПРЕДЛОГИ_ЦЕПОЧКИ:
                    длина += 1
            if длина > МАКС_ЦЕПОЧКА:
                нашли.append((номер, f"цепочка из {длина} существительных, нужно не больше {МАКС_ЦЕПОЧКА}"))
            i = j
        else:
            i += 1
    return нашли


def проверка_брифа(текст: str) -> list[tuple[int, str]]:
    """П8: стоп или «Не трогаем» после первого шага."""
    нашли = []
    первый_шаг = None
    в_коде = False
    начало = 0
    строки = текст.splitlines()
    if строки and строки[0].strip() == "---":
        for j in range(1, len(строки)):
            if строки[j].strip() == "---":
                начало = j + 1
                break
    for n in range(начало, len(строки)):
        с = строки[n]
        if с.lstrip().startswith("```"):
            в_коде = not в_коде
            continue
        if в_коде:
            continue
        if первый_шаг is None:
            if НАЧАЛО_ШАГА.match(с):
                первый_шаг = n + 1
            continue
        голая = убрать_разметку(с).strip().lstrip("#").strip()
        if СТОП_В_НАЧАЛЕ.match(голая):
            нашли.append((n + 1, f"стоп или «не трогаем» после шага (шаг начат в строке {первый_шаг}): поставь до шагов"))
    return нашли


def разобрать_отчёт(текст: str):
    """Возвращает (поля [(имя, номер, значение)], лишние [(номер, имя)], номера строк полей ветка и проверка)."""
    поля: list[list] = []
    лишние = []
    исключить: set[int] = set()
    текущее = None
    for n, с in enumerate(текст.splitlines(), 1):
        if с.lstrip().startswith("```"):
            continue
        м = re.match(r"^\s*(ветка|сделал|не смог|проверка)\s*:\s*(.*)$", с, re.I)
        if м:
            текущее = [м.group(1).lower(), n, м.group(2)]
            поля.append(текущее)
        elif re.match(r"^\s*предположение\s*:", с, re.I):
            текущее = None
        else:
            чужое = re.match(r"^([а-яёa-z][а-яёa-z ]{0,20}):\s{2,}\S", с, re.I)
            if чужое:
                лишние.append((n, чужое.group(1).strip().lower()))
                текущее = None
            elif текущее is not None and с.strip():
                текущее[2] += "\n" + с.strip()
        if текущее is not None and текущее[0] in ("ветка", "проверка"):
            исключить.add(n)
    return поля, лишние, исключить


def проверка_отчёта(текст: str) -> list[tuple[int, str]]:
    нашли = []
    поля, лишние, _ = разобрать_отчёт(текст)
    имена = [п[0] for п in поля]
    for имя in ПОЛЯ_ОТЧЁТА:
        if имена.count(имя) == 0:
            нашли.append((1, f"в отчёте нет поля «{имя}»"))
        elif имена.count(имя) > 1:
            n = [п[1] for п in поля if п[0] == имя][1]
            нашли.append((n, f"поле «{имя}» повторено"))
    for n, имя in лишние:
        нашли.append((n, f"лишнее поле «{имя}»: в отчёте ровно 4 поля"))
    if sorted(set(имена)) == sorted(ПОЛЯ_ОТЧЁТА) and len(имена) == 4 and имена != list(ПОЛЯ_ОТЧЁТА):
        нашли.append((поля[0][1], "поля идут не в порядке ветка / сделал / не смог / проверка"))
    for имя, n, значение in поля:
        if not значение.strip() or re.fullmatch(r"<[^>]*>", значение.strip()):
            нашли.append((n, f"поле «{имя}» пустое: пиши «—»"))
    ветка = next((п for п in поля if п[0] == "ветка"), None)
    if ветка and ветка[2].strip() and not re.fullmatch(r"<[^>]*>", ветка[2].strip()):
        значение = ветка[2].strip()
        if значение in ("—", "-"):
            пояснение = " ".join(п[2] for п in поля if п[0] in ("сделал", "не смог"))
            if not НЕТ_КОММИТА.search(пояснение):
                нашли.append((ветка[1], "ветка «—» без пояснения в «сделал» или «не смог», что коммита нет"))
        else:
            токены = [t.strip("()[],;`") for t in значение.split()]
            if not any(ХЭШ.fullmatch(t) for t in токены[1:]):
                нашли.append((ветка[1], "в поле ветка нет хэша коммита (7–40 знаков 0-9a-f)"))
    return нашли


def проверить(текст: str, уровень: str = "полный", вид: str = "текст",
              словарь: Словарь | None = None) -> list[tuple[int, str]]:
    """Возвращает отсортированные пары (номер строки, что не так)."""
    движок = Движок(словарь or загрузить_словарь(None))
    полный = уровень == "полный"
    нашли: list[tuple[int, str]] = []
    исключить: set[int] = set()
    if вид == "отчёт":
        исключить = разобрать_отчёт(текст)[2]
        if полный:
            нашли += проверка_отчёта(текст)
    if вид == "бриф" and полный:
        нашли += проверка_брифа(текст)
    for n, с in строки_для_проверки(текст, пропускать_код=(вид != "отчёт")):
        if n in исключить:
            continue
        чистая = замаскировать(убрать_разметку(с))
        нашли += проверка_слов(движок, n, чистая)
        нашли += проверка_чисел(движок, n, чистая)
        if полный:
            нашли += проверка_длины(n, чистая)
            нашли += проверка_цепочки(n, чистая)
    return sorted(set(нашли))


