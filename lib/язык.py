        случай("синоним проекта не действует без проекта", "Запусти линтер.", None)
        if нашлось("Отдай квота.", "квота", с_проектом) is False:
            беды.append("синоним из базового словаря не ловится при проектном")
        случай("синоним в кавычках не ловит", "Плохо: «таск».", None)
        # П2: расплывчатые слова
        случай("расплывчатое ловит", "Сделай это быстро.", "быстро")
        случай("расплывчатое «база» ловит", "Открой база.", "«база»")
        случай("расплывчатое внутри термина не ловит", "Открой базу знаний. Открой база знаний.", None)
        случай("падежная форма ловит", "1. Прогони задачу на базе proc.", "«база»")
        случай("падежная форма с заглавной ловит", "Базу открой.", "«база»")
        случай("падежная форма таск ловит", "Отдай таска работнику.", "таск")
        случай("однокоренное «базовый» не ловит", "Базовый режим. Базовые правила.", None)
