def кратко() -> int:
    """Краткие правила для хука SessionStart. Код выхода 0 всегда."""
    путь = Path(__file__).resolve().parent / "язык" / "правила.md"
    print("Язык (облегчённый уровень):")
    print("1. Термин — по словарю: одно понятие, одно слово.")
    print("2. Число — с единицей (5 мин, 3 файла).")
    print("3. Условие — до действия: «если X, сделай Y».")
    print("4. Без расплывчатых слов (быстро, вроде, как-нибудь).")
    print(f"Полные правила: {путь}")
    return 0


def главная(аргументы: list[str] | None = None) -> int:
    р = argparse.ArgumentParser(description="Сторож текста: правила Плексус-STE.")
    р.add_argument("файл", nargs="?", help="путь к файлу или - для stdin")
    р.add_argument("--уровень", choices=["полный", "облегчённый"], default="полный")
    р.add_argument("--вид", choices=["бриф", "отчёт", "текст"], default="текст")
    р.add_argument("--проект", help="папка vault с проектным словарём")
    р.add_argument("--самопроверка", action="store_true")
    р.add_argument("--кратко", action="store_true",
                   help="не больше 6 строк: облегчённые правила и путь к правила.md")
    а = р.parse_args(аргументы)
    if а.кратко:
        return кратко()
    if а.самопроверка:
        return самопроверка()
    if not а.файл:
        р.print_usage(sys.stderr)
        return 2
    try:
        if а.файл == "-":
            текст = sys.stdin.read()
        else:
            текст = Path(а.файл).read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError) as e:
        print(f"{а.файл}:0: не удалось прочитать: {e}", file=sys.stderr)
        return 2
    словарь = загрузить_словарь(Path(а.проект) if а.проект else None)
    нашли = проверить(текст, а.уровень, а.вид, словарь)
    for n, что in нашли:
        print(f"{а.файл}:{n}: {что}")
    return 1 if (нашли and а.уровень == "полный") else 0


