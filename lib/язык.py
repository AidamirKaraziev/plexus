        случай("стоп до шагов не ловит", "Цель: x.\nСтоп: не трогай skills/\n1. Прочитай файл.", None, вид="бриф")
        случай("стоп после шага не ловит в тексте", "1. Прочитай файл.\nСтоп: не трогай skills/", None)
        # П1: запрещённые синонимы
        случай("синоним ловит", "Отдай таск работнику.", "таск")
