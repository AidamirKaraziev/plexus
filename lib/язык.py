#!/usr/bin/env python3
"""Сторож текста: ловит нарушения правил Плексус-STE в брифе, отчёте и заметке.

Правила — `lib/язык/правила.md`, термины и расплывчатые слова —
`lib/язык/словарь.md` и проектный `vault/словарь.md` (проектный дополняет
базовый, при совпадении термина действует проектный).

Запуск:
    python3 lib/язык.py [--уровень полный|облегчённый] [--вид бриф|отчёт|текст]
                        [--проект <vault>] <файл|->
    python3 lib/язык.py --самопроверка

Вывод нарушения: `<файл>:<строка>: <что не так>`.
Коды выхода: 0 — чисто (или облегчённый уровень, он только предупреждает),
1 — полный уровень нашёл нарушения, 2 — не удалось прочитать вход.

Принцип: ложное срабатывание хуже пропуска. Сомнительный случай не ругаем.
Только стандартная библиотека.
"""
import argparse
import contextlib
