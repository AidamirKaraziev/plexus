        случай("длина ловит", ДЛИННАЯ_ФРАЗА, "фраза из 25 слов")
        случай("длина не ловит короткую", "Прочитай файл. Поправь ошибки.", None)
        случай("длина не ловит код", "`" + " ".join(["слово"] * 30) + "`.", None)
        случай("длина не ловит блок кода", "```\n" + ДЛИННАЯ_ФРАЗА + "\n```", None)
        # П9: родительная цепочка
