def _добавить(путь: Path, каталог: str, сессия: str, записи: list[dict]) -> None:
    файл = путь / каталог / f"{сессия}.jsonl"
    файл.parent.mkdir(parents=True, exist_ok=True)
    with файл.open("a", encoding="utf-8") as f:
        for з in записи:
            f.write(json.dumps(з, ensure_ascii=False) + "\n")


def _человек(текст: str) -> dict:
    return {"type": "user", "message": {"role": "user", "content": текст}}


def _текст_ассистента(текст: str) -> dict:
    return {"type": "assistant", "message": {"role": "assistant", "content": [{"type": "text", "text": текст}]}}


def _правка_ассистента(имя: str, путь_файла: str, id_: str) -> dict:
    return {
        "type": "assistant",
        "message": {"role": "assistant", "content": [
            {"type": "tool_use", "id": id_, "name": имя, "input": {"file_path": путь_файла}},
        ]},
    }


def _результат(id_: str) -> dict:
    return {"type": "user", "message": {"role": "user", "content": [
        {"type": "tool_result", "tool_use_id": id_, "content": "ок"},
    ]}}


