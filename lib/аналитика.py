#!/usr/bin/env python3
"""Свод транскриптов сессий Claude Code в выжимку для аналитика.

Сырьё — ~/.claude/projects/*/*.jsonl, все проекты. Сырьё огромно (за
сентябрь ~450k токенов на сессию), поэтому в окно работника оно никогда
не попадает целиком — только этот свод и точечные куски по его
указателям (проект · сессия · строка).

Формат данных (измерено на реальных транскриптах):
- строка jsonl имеет поле `type`: user / assistant / attachment / system / …
- `message.content` бывает строкой или списком блоков
- реплика человека отличается от результата инструмента тем, что в
  списке блоков нет блока с `type == "tool_result"`
- вызов скилла виден по подстроке `<command-name>` в тексте реплики

Приватность: транскрипты личных проектов (cortex, KMZ, amo-crm, aidamir)
читаются только на метрики — какой скилл, сколько раундов вопросов, был
ли `/закрыть`. Текст реплик из них в выжимку не попадает никогда —
только из проектов разработки.

    python3 lib/аналитика.py --свод [--транскрипты DIR] [--курсор FILE]
    python3 lib/аналитика.py --порог [--курсор FILE]
    python3 lib/аналитика.py --роль ФАЙЛ
    python3 lib/аналитика.py --самопроверка
"""
import argparse
import contextlib
import io
import json
import math
import re
import sys
import tempfile
from pathlib import Path

ПОРОГ_ПО_УМОЛЧАНИЮ = 10
БЮДЖЕТ_ТОКЕНОВ = 20_000
ЛИЧНЫЕ_ПРОЕКТЫ = ("cortex", "kmz", "amo-crm", "amo_crm", "aidamir")

КОМАНДА = re.compile(r"<command-name>\s*([^<\s][^<]*?)\s*</command-name>")
ВОЗРАЖЕНИЕ = re.compile(
    r"не то\b|не так\b|неправильно|не надо\b|отмени|верни как было|"
    r"не годится|так не пойдёт|переделай|не устраивает|так не годится",
    re.I,
)
ПРАВКА_СЛОВА = re.compile(
    r"сам\w*\s+(поправ\w*|исправ\w*|подправ\w*|отредактир\w*|измен\w*)", re.I
)


# ---------- пути и хранение ----------

def репозиторий() -> Path:
    return Path(__file__).resolve().parent.parent


def путь_курсора_по_умолчанию() -> Path:
    return репозиторий() / ".claude" / "аналитика-курсор.json"


def путь_транскриптов_по_умолчанию() -> Path:
    return Path.home() / ".claude" / "projects"


def читать_курсор(путь: Path) -> dict:
    if not путь.exists():
        return {"порог": ПОРОГ_ПО_УМОЛЧАНИЮ, "сигналов": 0, "файлы": {}}
    try:
        данные = json.loads(путь.read_text(encoding="utf-8"))
    except json.JSONDecodeError:
        return {"порог": ПОРОГ_ПО_УМОЛЧАНИЮ, "сигналов": 0, "файлы": {}}
    данные.setdefault("порог", ПОРОГ_ПО_УМОЛЧАНИЮ)
    данные.setdefault("сигналов", 0)
    данные.setdefault("файлы", {})
    return данные


def писать_курсор(путь: Path, данные: dict) -> None:
    путь.parent.mkdir(parents=True, exist_ok=True)
    путь.write_text(
        json.dumps(данные, ensure_ascii=False, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )


_КОДИРОВЩИК = None
_КОДИРОВЩИК_ПРОБОВАЛИ = False


def _кодировщик():
    """tiktoken, если он есть в окружении; иначе None — тогда честная
    оценка по символам с учётом кириллицы (см. оценка_токенов)."""
    global _КОДИРОВЩИК, _КОДИРОВЩИК_ПРОБОВАЛИ
    if not _КОДИРОВЩИК_ПРОБОВАЛИ:
        _КОДИРОВЩИК_ПРОБОВАЛИ = True
        try:
            import tiktoken
            _КОДИРОВЩИК = tiktoken.get_encoding("cl100k_base")
        except Exception:
            _КОДИРОВЩИК = None
    return _КОДИРОВЩИК


def оценка_токенов(текст: str) -> int:
    """Честный размер в токенах. Если доступен tiktoken — считает им (как
    у модели). Иначе — консервативная оценка по символам: англоцентричная
    «символов/4» занижает кириллицу вдвое, поэтому кириллические символы
    считаются по ~2 символа на токен, латиница и цифры — по ~4."""
    кодировщик = _кодировщик()
    if кодировщик is not None:
        return len(кодировщик.encode(текст))
    кириллица = sum(1 for c in текст if "а" <= c.lower() <= "я" or c.lower() in "ёй")
    остальное = len(текст) - кириллица
    return math.ceil(кириллица / 2 + остальное / 4)


def личный_проект(имя_каталога: str) -> bool:
    низ = имя_каталога.lower()
    return any(м in низ for м in ЛИЧНЫЕ_ПРОЕКТЫ)


# ---------- разбор записей транскрипта ----------

def блоки_содержимого(запись: dict) -> list:
    содержимое = запись.get("message", {}).get("content")
    if isinstance(содержимое, str):
        return [{"type": "text", "text": содержимое}]
    if isinstance(содержимое, list):
        return содержимое
    return []


def текст_реплики(запись: dict) -> str:
    части = []
    for блок in блоки_содержимого(запись):
        if isinstance(блок, dict) and блок.get("type") == "text":
            части.append(блок.get("text", ""))
        elif isinstance(блок, str):
            части.append(блок)
    return "\n".join(части)


def результат_инструмента(запись: dict) -> bool:
    return any(
        isinstance(б, dict) and б.get("type") == "tool_result"
        for б in блоки_содержимого(запись)
    )


def реплика_человека(запись: dict) -> bool:
    return запись.get("type") == "user" and not результат_инструмента(запись)


def вызовы_инструментов(запись: dict) -> list[dict]:
    if запись.get("type") != "assistant":
        return []
    return [
        б for б in блоки_содержимого(запись)
        if isinstance(б, dict) and б.get("type") == "tool_use"
    ]


def файл_из_вызова(блок: dict) -> str | None:
    вход = блок.get("input") or {}
    for ключ in ("file_path", "path", "notebook_path"):
        if ключ in вход and вход[ключ]:
            return вход[ключ]
    return None


def скиллы_в_реплике(текст: str) -> list[str]:
    return [м.strip() for м in КОМАНДА.findall(текст)]


# ---------- сигналы на уровне сессии ----------

def _сигнал_закрытия(записи: list[tuple[int, dict]], проект: str, сессия: str) -> dict | None:
    if not записи:
        return None
    закрыто = any(
        реплика_человека(з) and "закрыть" in скиллы_в_реплике(текст_реплики(з))
        for _, з in записи
    )
    if закрыто:
        return None
    последняя = записи[-1][0]
    return {
        "тип": "оборвалась", "проект": проект, "сессия": сессия,
        "смещение": последняя, "значение": "нет /закрыть",
    }


def разобрать_сессию(
    записи: list[tuple[int, dict]], проект: str, сессия: str, разработка: bool,
) -> list[dict]:
    """Сигналы из новых строк одной сессии. Для не-dev проектов — только
    метрики (скилл, число раундов, факт /закрыть), без текста реплик."""
    if not записи:
        return []
    сигналы = []

    # какие скиллы звались и в каком порядке
    порядок = []
    for i, з in записи:
        if реплика_человека(з):
            for имя in скиллы_в_реплике(текст_реплики(з)):
                порядок.append((i, имя))
    if порядок:
        сигналы.append({
            "тип": "скиллы", "проект": проект, "сессия": сессия,
            "смещение": порядок[0][0],
            "значение": " → ".join(имя for _, имя in порядок),
        })

    # раунды вопросов до начала работы (первый tool_use ассистента)
    начало_работы = next((i for i, з in записи if вызовы_инструментов(з)), None)
    if начало_работы is not None:
        первая_строка = записи[0][0]
        раунды = sum(
            1 for i, з in записи
            if i < начало_работы and i > первая_строка and реплика_человека(з)
        )
        if раунды:
            сигналы.append({
                "тип": "вопросы-до-работы", "проект": проект, "сессия": сессия,
                "смещение": начало_работы, "значение": раунды,
            })

    if not разработка:
        сигнал = _сигнал_закрытия(записи, проект, сессия)
        if сигнал:
            сигналы.append(сигнал)
        return сигналы

    # где человек возражал ответу
    for i, з in записи:
        if реплика_человека(з):
            текст = текст_реплики(з)
            if ВОЗРАЖЕНИЕ.search(текст):
                сигналы.append({
                    "тип": "возражение", "проект": проект, "сессия": сессия,
                    "смещение": i, "значение": текст.strip()[:140],
                })

    # где правил файл сразу после правки ассистента
    for idx, (i, з) in enumerate(записи):
        правки = [б for б in вызовы_инструментов(з) if б.get("name") in ("Edit", "Write", "NotebookEdit")]
        if not правки:
            continue
        файлы = {ф for б in правки if (ф := файл_из_вызова(б))}
        if not файлы:
            continue
        for i2, з2 in записи[idx + 1:]:
            if реплика_человека(з2):
                текст2 = текст_реплики(з2)
                if ПРАВКА_СЛОВА.search(текст2) and any(ф in текст2 for ф in файлы):
                    сигналы.append({
                        "тип": "правка-вслед", "проект": проект, "сессия": сессия,
                        "смещение": i2, "значение": текст2.strip()[:140],
                    })
                break

    сигнал = _сигнал_закрытия(записи, проект, сессия)
    if сигнал:
        сигналы.append(сигнал)
    return сигналы


# ---------- обход файлов и курсор ----------

def найти_транскрипты(корень: Path) -> list[Path]:
    if not корень.exists():
        return []
    return sorted(корень.glob("*/*.jsonl"))


def ключ_файла(путь: Path, корень: Path) -> str:
    return str(путь.relative_to(корень))


def свести(транскрипты: Path, курсор: dict) -> list[dict]:
    """Разбирает новые с курсора строки, двигает курсор['файлы'] на месте,
    возвращает список новых сигналов (курсор['сигналов'] не трогает)."""
    все_сигналы = []
    for файл in найти_транскрипты(транскрипты):
        ключ = ключ_файла(файл, транскрипты)
        обработано = курсор["файлы"].get(ключ, 0)
        with файл.open(encoding="utf-8") as f:
            строки_файла = f.readlines()
        if len(строки_файла) <= обработано:
            continue
        новые = []
        for i in range(обработано, len(строки_файла)):
            строка = строки_файла[i].strip()
            if not строка:
                continue
            try:
                новые.append((i, json.loads(строка)))
            except json.JSONDecodeError:
                continue
        каталог = файл.parent.name
        сессия = файл.stem
        все_сигналы.extend(
            разобрать_сессию(новые, каталог, сессия, not личный_проект(каталог))
        )
        курсор["файлы"][ключ] = len(строки_файла)
    return все_сигналы


# ---------- сборка выжимки с бюджетом токенов ----------

ЗАГОЛОВКИ = {
    "скиллы": "Скиллы и порядок вызова",
    "вопросы-до-работы": "Раунды вопросов до начала работы",
    "возражение": "Человек возразил ответу",
    "правка-вслед": "Правка файла сразу после ассистента",
    "оборвалась": "Сессия оборвалась без /закрыть",
}


def _группировать(сигналы: list[dict]) -> dict[str, dict[str, list[tuple]]]:
    """тип -> значение -> [(проект, сессия, смещение), ...] — сигналы с
    одинаковым значением схлопываются в одну группу, счётчик встреч не
    теряется, указатели на каждое вхождение остаются."""
    группы: dict[str, dict[str, list[tuple]]] = {}
    for с in сигналы:
        (группы.setdefault(с["тип"], {}).setdefault(с["значение"], [])
         .append((с["проект"], с["сессия"], с["смещение"])))
    return группы


def _строка_группы(значение, места: list[tuple], лимит_примеров: int) -> str:
    показать = места[:лимит_примеров]
    примеры = ", ".join(f"{п}·{с}·строка {о}" for п, с, о in показать)
    if len(места) > лимит_примеров:
        примеры += f" [+{len(места) - лимит_примеров} ещё]"
    return f"- {значение} — встречалось {len(места)} раз · {примеры}"


def _текст_выжимки(
    сигналы: list[dict], всего_сигналов: int,
    лимит_групп: int, лимит_примеров: int, обрезано: bool,
) -> str:
    группы = _группировать(сигналы)

    части = [
        "# Свод транскриптов",
        f"новых сигналов: {len(сигналы)} · всего накоплено: {всего_сигналов}",
    ]
    if обрезано:
        части.append("(сокращено по бюджету токенов)")
    части.append("")
    for тип, заголовок in ЗАГОЛОВКИ.items():
        по_значению = группы.get(тип, {})
        if not по_значению:
            continue
        отсортированные = sorted(по_значению.items(), key=lambda kv: -len(kv[1]))
        показать = отсортированные[:лимит_групп]
        всего_видов = len(отсортированные)
        всего_вхождений = sum(len(места) for места in по_значению.values())
        части.append(f"## {заголовок} ({всего_видов} видов · {всего_вхождений} сигналов)")
        for значение, места in показать:
            части.append(_строка_группы(значение, места, лимит_примеров))
        if всего_видов > лимит_групп:
            части.append(f"… и ещё {всего_видов - лимит_групп} видов")
        части.append("")
    return "\n".join(части).rstrip() + "\n"


def собрать_выжимку(сигналы: list[dict], всего_сигналов: int) -> str:
    """Группирует однотипные сигналы по значению — счётчик встреч и
    указатели на представителей вместо строки на каждое вхождение — и
    ужимает счётчик групп/примеров, пока честная оценка в токенах
    (см. оценка_токенов) не уложится в БЮДЖЕТ_ТОКЕНОВ, при любом числе
    входных сигналов."""
    лимит_групп, лимит_примеров = 200, 5
    текст = _текст_выжимки(сигналы, всего_сигналов, лимит_групп, лимит_примеров, обрезано=False)
    while оценка_токенов(текст) > БЮДЖЕТ_ТОКЕНОВ and (лимит_групп > 1 or лимит_примеров > 1):
        if лимит_групп > 1:
            лимит_групп = max(1, лимит_групп // 2)
        if лимит_примеров > 1:
            лимит_примеров = max(1, лимит_примеров // 2)
        текст = _текст_выжимки(сигналы, всего_сигналов, лимит_групп, лимит_примеров, обрезано=True)
    if оценка_токенов(текст) > БЮДЖЕТ_ТОКЕНОВ:
        # крайний предохранитель: режем по символам, пока честный счёт не сойдётся
        низ, верх = 0, len(текст)
        while низ < верх:
            середина = (низ + верх + 1) // 2
            if оценка_токенов(текст[:середина]) <= БЮДЖЕТ_ТОКЕНОВ - 20:
                низ = середина
            else:
                верх = середина - 1
        текст = текст[:низ].rstrip() + "\n… обрезано по бюджету\n"
    return текст


# ---------- команды ----------

def печать_свода(транскрипты: Path, курсор_путь: Path) -> int:
    курсор = читать_курсор(курсор_путь)
    новые_сигналы = свести(транскрипты, курсор)
    курсор["сигналов"] = курсор.get("сигналов", 0) + len(новые_сигналы)
    выжимка = собрать_выжимку(новые_сигналы, курсор["сигналов"])
    писать_курсор(курсор_путь, курсор)
    print(выжимка)
    print(f"выжимка: {оценка_токенов(выжимка)} токенов")
    return 0


def печать_порога(курсор_путь: Path) -> int:
    курсор = читать_курсор(курсор_путь)
    n = курсор.get("сигналов", 0)
    порог = курсор.get("порог", ПОРОГ_ПО_УМОЛЧАНИЮ)
    звать = "да" if n >= порог else "нет"
    print(f"сигналов {n} · порог {порог} · звать: {звать}")
    return 0


