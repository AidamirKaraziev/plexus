def проверить_роль(путь: Path) -> int:
    if not путь.exists():
        print(f"✗ файл роли не найден: {путь}")
        return 1
    текст = путь.read_text(encoding="utf-8").lower()
    беды = 0
    for имя, проверка in ПУНКТЫ_РОЛИ:
        if проверка(текст):
            print(f"✓ {имя}")
        else:
            print(f"✗ {имя}")
            беды += 1
    if беды:
        print(f"роль: {беды} пунктов не найдено")
        return 1
    print("роль: все пункты найдены")
    return 0


