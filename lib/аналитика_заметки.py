def main() -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    ap = argparse.ArgumentParser(add_help=True)
    ap.add_argument("модули", nargs="?", help="папка модули с карточками и аналитикой")
    ap.add_argument("--код", help="корень репозитория — сверить папки backend/internal/modules")
    ap.add_argument("--самопроверка", action="store_true")
    a = ap.parse_args()

    if a.самопроверка:
        return самопроверка()
    if not a.модули:
        ap.error("нужна папка модули или --самопроверка")
    корень = Path(a.модули)
    if not корень.is_dir():
        print(f"{корень.as_posix()}: нет такой папки")
        return 1
    код = Path(a.код) if a.код else None
    if код is not None and not код.is_dir():
        print(f"{код.as_posix()}: нет такой папки корня репозитория")
        return 1
    беды = проверить(корень.resolve(), код)
    if беды:
        for путь, что in беды:
            print(f"{путь}: {что}")
        return 1
    print("ок")
    return 0


if __name__ == "__main__":
    sys.exit(main())
