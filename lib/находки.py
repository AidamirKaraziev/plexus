#!/usr/bin/env python3
"""Проверяет отчёт агента architect (режим «аудит») по формату из agents/architect.md.

Шапка: область, балл, проверено, не проверено. Разделы: «## находки»,
«## спорное», «## правила, которых не хватает» (или «## документы» для
области «база знаний»). Находка: «### <тяжесть> · <суть>» и поля где,
правило, доказательство, надо, объём. Балл сверяется с правилом подсчёта.
Печатает сводку; код 0 — формат соблюдён. Файл отчёта: $1, иначе stdin.
"""
import re
import sys

ТЯЖЕСТЬ = ("критично", "важно", "мелочь")
ПОЛЯ = ("где", "правило", "доказательство", "надо", "объём")

текст = open(sys.argv[1], encoding="utf-8").read() if len(sys.argv) > 1 else sys.stdin.read()
ошибки = []

шапка = {}
for п in ("область", "балл", "проверено", "не проверено"):
    м = re.search(rf"^{п}: (.+)$", текст, re.M)
    if м:
        шапка[п] = м.group(1).strip()
    else:
        ошибки.append(f"шапка: нет «{п}:»")

разделы = dict(
    (м.group(1).strip(), м.start())
    for м in re.finditer(r"^## (.+)$", текст, re.M)
)
знания = "документы" in разделы
нужны = ("документы",) if знания else ("находки", "спорное", "правила, которых не хватает")
for р in нужны:
    if р not in разделы:
        ошибки.append(f"нет раздела «## {р}»")


def раздел(имя):
    if имя not in разделы:
        return ""
    начало = разделы[имя]
    дальше = [н for н in разделы.values() if н > начало]
    return текст[начало:min(дальше) if дальше else len(текст)]


счёт = dict.fromkeys(ТЯЖЕСТЬ, 0)
if not знания:
    for блок in re.split(r"^### ", раздел("находки"), flags=re.M)[1:]:
        заголовок, *строки = блок.strip().splitlines()
        тяжесть = заголовок.split(" · ")[0].strip()
        if тяжесть not in ТЯЖЕСТЬ:
            ошибки.append(f"находка «{заголовок}»: тяжесть не из {ТЯЖЕСТЬ}")
        else:
            счёт[тяжесть] += 1
        поля = {м.group(1): м.group(2) for м in (re.match(r"- (\S+): (.+)", с) for с in строки) if м}
        нет = [п for п in ПОЛЯ if not поля.get(п, "").strip()]
        if нет:
            ошибки.append(f"находка «{заголовок}»: нет {', '.join(нет)}")
        elif not re.match(r"[SML]\b", поля["объём"]):
            ошибки.append(f"находка «{заголовок}»: объём не S/M/L")

    к, в = счёт["критично"], счёт["важно"]
    ожидаем = 1 if к >= 3 else 2 if к else 3 if в > 3 else 4 if в else 5
    м = re.match(r"(\d)", шапка.get("балл", ""))
    if м and int(м.group(1)) not in (ожидаем, 1):
        # 1 допустим и без трёх критичных: «в области нет ни одного барьера»
        ошибки.append(f"балл {м.group(1)}, по правилу {ожидаем} (критично {к}, важно {в})")

print(f"область {шапка.get('область', '?')} · балл {шапка.get('балл', '?').split(' ')[0]} · "
      + ("документы" if знания else " · ".join(f"{т} {н}" for т, н in счёт.items())))
for о in ошибки:
    print("  ✗", о)
sys.exit(1 if ошибки else 0)
